#!/usr/bin/env python3
"""Merge the European OUI presets into src/oui_eu.h.

Only the regional European presets are used, plus two extras: the Flock Safety entries of
global.json (the rest of it is mostly North American) and Ring / drone makers. Belgium has
no app preset yet; its list lives in presets/belgium.json and the
Ring / DJI / Parrot / Skydio list in presets/camera_drone.json (same format).
Every prefix in those two files is checked against the IEEE table the app bundles. A prefix that appears in several countries is kept once, with
its highest score. Run from anywhere:  python3 tools/gen_oui.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PRESETS = ROOT / "presets/app"  # copies of RF Sentinel's oui_presets
OUT = ROOT / "src/oui_eu.h"
EUROPE = ["uk", "france", "germany", "italy", "netherlands", "portugal", "spain", "sweden", "belgium",
          "flock", "cameras"]
SOURCE = {c: PRESETS / f"{c}.json" for c in EUROPE}
SOURCE["belgium"] = ROOT / "presets/belgium.json"
SOURCE["flock"] = PRESETS / "global.json"  # only the entries whose label names Flock
SOURCE["cameras"] = ROOT / "presets/camera_drone.json"
CHECKED = {"belgium", "cameras"}  # hand-written lists: label must match the IEEE registrant
IEEE = ROOT / "data/oui.tsv"  # IEEE registry, as bundled by RF Sentinel
ISO = {"uk": "UK", "france": "FR", "germany": "DE", "italy": "IT", "netherlands": "NL",
       "portugal": "PT", "spain": "ES", "sweden": "SE", "belgium": "BE", "flock": "FLOCK", "cameras": "CAM"}
CATS = {"BODY_CAM": "CAT_BODYCAM", "ALPR": "CAT_ALPR", "PUBLIC_SAFETY": "CAT_POLICE",
        "CAMERA": "CAT_CAMERA", "DRONE": "CAT_DRONE"}
FLOCK_MAKER = {"Universal Global Scientific (USI)": "USI"}
SHORT = {  # screen is 160 px wide: keep vendor names short
    "EADS / Airbus TETRAPOL radio": "Airbus TETRAPOL",
    "Airbus Defence and Space": "Airbus DS",
    "Leonardo Sistemi Integrati": "Leonardo",
    "Leonardo SpA": "Leonardo",
    "Idemia Public Security France": "Idemia",
    "Jenoptik Advanced Systems": "Jenoptik",
    "Elsag Datamat": "Elsag",
    "Selex Communications": "Selex",
    "Zepcam body camera": "Zepcam",
    "Axon body camera": "Axon",
}


def short_name(label: str) -> str:
    m = re.match(r"(.+?) (?:module|radio) seen on Flock", label)
    if m:  # community-list chip makers: "Liteon (Flock chip)"
        return f"{FLOCK_MAKER.get(m.group(1), m.group(1))} (Flock chip)"
    name = re.split(r" - | \(", label)[0].strip()
    return SHORT.get(name, name)


def check_registrant(e, country):
    """The label's brand must appear in the IEEE registrant of the block, so a typo can't flag the wrong maker."""
    table = {}
    for ln in IEEE.read_text().splitlines():
        if "\t" in ln and not ln.startswith("#"):
            k, v = ln.split("\t", 1)
            table[k] = v
    key = e["prefix"].replace(":", "").upper()
    registrant = table.get(key)
    brand = re.split(r" - | \(| /", e["label"])[0].split()[0]
    if registrant is None or brand.lower() not in registrant.lower():
        raise SystemExit(f'{country}: {e["prefix"]} label "{e["label"]}" vs IEEE "{registrant}"')


merged = {}
for country in EUROPE:
    for e in json.loads(SOURCE[country].read_text()):
        if country == "flock" and "Flock" not in e["label"]:
            continue
        key = e["prefix"].upper()
        if not re.fullmatch(r"[0-9A-F]{2}(:[0-9A-F]{2}){2}(:[0-9A-F]{2})*(:[0-9A-F])?", key):
            raise SystemExit(f"{country}: rule is not an address prefix: {key}")
        if country in CHECKED:
            check_registrant(e, country)
        cur = merged.get(key)
        if cur is None or e["score"] > cur["score"]:
            merged[key] = {"score": e["score"], "cat": CATS[e["category"]], "name": short_name(e["label"]),
                           "countries": set(cur["countries"]) if cur else set()}
        merged[key]["countries"].add(country)

rows = []
for key, e in sorted(merged.items(), key=lambda kv: (-kv[1]["score"], kv[0])):
    hexdigits = key.replace(":", "")
    rows.append(f'  {{0x{hexdigits}ULL, {len(hexdigits)}, {e["score"]}, {e["cat"]}, "{e["name"]}"}},'
                f'  // {key} {",".join(sorted(ISO[c] for c in e["countries"]))}')

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// GENERATED by tools/gen_oui.py from the European presets in\n"
    "// presets/app/ and presets/ (" + ", ".join(EUROPE) + "). Do not edit.\n"
    "#pragma once\n#include <stdint.h>\n\n"
    "enum Cat : uint8_t { CAT_BODYCAM, CAT_ALPR, CAT_POLICE, CAT_CAMERA, CAT_DRONE };\n\n"
    "struct OuiEntry {\n  uint64_t val;     // the prefix digits as one number\n"
    "  uint8_t nibbles;  // hex digits in the prefix: 6 = 24-bit OUI, 7 = 28-bit, 9 = 36-bit\n"
    "  uint8_t score;    // app confidence, 0-100\n  Cat cat;\n  const char* name;\n};\n\n"
    "static const OuiEntry OUI_EU[] = {\n" + "\n".join(rows) + "\n};\n"
    "static const int OUI_EU_COUNT = sizeof(OUI_EU) / sizeof(OUI_EU[0]);\n"
)
print(f"{len(rows)} prefixes -> {OUT.relative_to(ROOT)}")
